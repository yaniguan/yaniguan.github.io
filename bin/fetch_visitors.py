#!/usr/bin/env python
"""Write per-country visitor counts from Google Analytics to _data/visitors.yml.

Run by .github/workflows/visitors.yml once a day. The homepage visitor map
(_includes/visitor_map.liquid) reads the file at build time, so the site never
talks to Google Analytics from the browser.

Inputs (environment):
    GA_PROPERTY_ID                  numeric GA4 property id
    GOOGLE_APPLICATION_CREDENTIALS  path to a service-account JSON key with
                                    Viewer access on that property
    VISITORS_SINCE                  first day to count, YYYY-MM-DD

Usage:
    python bin/fetch_visitors.py _data/visitors.yml

The file is rewritten only when the counts change, so a quiet day does not
produce a commit.
"""
import os
import sys

import pycountry
import yaml
from google.analytics.data_v1beta import BetaAnalyticsDataClient
from google.analytics.data_v1beta.types import (
    DateRange,
    Dimension,
    Metric,
    OrderBy,
    RunReportRequest,
)


def fetch(property_id, since):
    """Return [(alpha2, name, users)] for every country with at least one user."""
    client = BetaAnalyticsDataClient()
    request = RunReportRequest(
        property=f"properties/{property_id}",
        dimensions=[Dimension(name="countryId"), Dimension(name="country")],
        metrics=[Metric(name="totalUsers")],
        date_ranges=[DateRange(start_date=since, end_date="today")],
        order_bys=[OrderBy(metric=OrderBy.MetricOrderBy(metric_name="totalUsers"), desc=True)],
        limit=300,
    )
    rows = []
    for row in client.run_report(request).rows:
        alpha2, name = row.dimension_values[0].value, row.dimension_values[1].value
        users = int(row.metric_values[0].value)
        if users > 0:
            rows.append((alpha2, name, users))
    return rows


def to_record(alpha2, name, users):
    """Attach the ISO 3166-1 numeric code the world-atlas TopoJSON uses as id."""
    country = pycountry.countries.get(alpha_2=alpha2) if len(alpha2) == 2 else None
    return {
        "id": country.numeric if country else None,
        "code": alpha2 if country else None,
        "name": name,
        "users": users,
    }


def main(out_path):
    property_id = os.environ["GA_PROPERTY_ID"]
    since = os.environ["VISITORS_SINCE"]

    records = [to_record(*row) for row in fetch(property_id, since)]
    mapped = [r for r in records if r["id"]]
    data = {
        "since": since,
        # Users summed over countries; GA counts a user once per country, so a
        # traveller can appear twice. Close enough for a "visitors" line.
        "total_users": sum(r["users"] for r in records),
        "country_count": len(mapped),
        "unmapped_users": sum(r["users"] for r in records if not r["id"]),
        "countries": mapped,
    }

    text = (
        "# Generated by bin/fetch_visitors.py from Google Analytics; do not edit.\n"
        + yaml.safe_dump(data, sort_keys=False, allow_unicode=True)
    )
    old = open(out_path, encoding="utf-8").read() if os.path.exists(out_path) else ""
    if text == old:
        print("visitor counts unchanged")
        return
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {out_path}: {data['total_users']} users, {data['country_count']} countries")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
